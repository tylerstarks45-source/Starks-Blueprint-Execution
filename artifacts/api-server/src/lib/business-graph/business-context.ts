// Pure: no DB access.

import type {
  BusinessDependency,
  BusinessEdge,
  BusinessGraphSummary,
  BusinessHealth,
  BusinessKpi,
  BusinessNode,
} from "./types";
import { rankNodesByStrategicImportance, findCriticalRiskNodes } from "./node-engine";

// ── Identify business opportunities from graph state ─────────────────────────

function findOpportunities(
  nodes: BusinessNode[],
  kpis: BusinessKpi[],
  health: BusinessHealth | null,
): string[] {
  const opps: string[] = [];

  // Revenue opportunity: has product but no revenue_stream node
  const hasProduct = nodes.some((n) => ["product", "service"].includes(n.nodeType) && n.isActive);
  const hasRevenueStream = nodes.some((n) => n.nodeType === "revenue_stream" && n.isActive);
  if (hasProduct && !hasRevenueStream) {
    opps.push("Add a revenue stream node to track income generated by your products/services.");
  }

  // Automation opportunity: has processes but no automations
  const hasProcesses = nodes.some((n) => n.nodeType === "process" && n.isActive);
  const hasAutomations = nodes.some((n) => n.nodeType === "automation" && n.isActive);
  if (hasProcesses && !hasAutomations) {
    opps.push("Automate existing processes to improve operational efficiency.");
  }

  // KPI opportunity: no KPIs defined
  if (kpis.length === 0) {
    opps.push("Define KPIs to measure business performance and unlock health tracking.");
  }

  // Marketing opportunity: has customers but no funnel
  const hasCustomers = nodes.some((n) => ["customer", "lead"].includes(n.nodeType) && n.isActive);
  const hasFunnel = nodes.some((n) => n.nodeType === "funnel" && n.isActive);
  if (hasCustomers && !hasFunnel) {
    opps.push("Create a funnel node to optimize the customer acquisition path.");
  }

  // Growth opportunity: growth health is good but no growth KPI tracked
  if (health && health.growthHealth >= 0.6) {
    const hasGrowthKpi = kpis.some((k) => ["growth_rate", "mrr", "arr"].includes(k.kpiType));
    if (!hasGrowthKpi) {
      opps.push("Track growth KPIs (MRR, ARR, growth rate) to capture your growth momentum.");
    }
  }

  // Partnership opportunity: no partner nodes
  const hasPartner = nodes.some((n) => n.nodeType === "partner" && n.isActive);
  if (nodes.length >= 5 && !hasPartner) {
    opps.push("Explore strategic partnerships to expand market reach and capabilities.");
  }

  return opps.slice(0, 4);
}

// ── Assemble the summary ──────────────────────────────────────────────────────

export function assembleBizGraphSummary(opts: {
  business: { id: number; name: string };
  nodes: BusinessNode[];
  edges: BusinessEdge[];
  kpis: BusinessKpi[];
  health: BusinessHealth | null;
  deps: BusinessDependency[];
  lastActivityAt: Date | null;
}): BusinessGraphSummary {
  const { business, nodes, edges, kpis, health, deps, lastActivityAt } = opts;

  const activeNodes = nodes.filter((n) => n.isActive);
  const ranked = rankNodesByStrategicImportance(activeNodes);
  const criticalRisks = findCriticalRiskNodes(activeNodes);

  return {
    businessId: business.id,
    businessName: business.name,
    nodeCount: activeNodes.length,
    edgeCount: edges.filter((e) => e.isActive).length,
    topNodes: ranked.slice(0, 5).map((n) => ({
      id: n.id,
      name: n.name,
      nodeType: n.nodeType,
      health: n.health,
      priority: n.priority,
      strategicImportance: n.strategicImportance,
    })),
    criticalRisks: criticalRisks.slice(0, 3).map((n) => ({
      id: n.id,
      name: n.name,
      nodeType: n.nodeType,
      risk: n.risk,
    })),
    currentKpis: kpis.slice(0, 6).map((k) => ({
      id: k.id,
      name: k.name,
      kpiType: k.kpiType,
      currentValue: k.currentValue,
      unit: k.unit,
      trend: k.trend,
      isHealthy: k.isHealthy,
    })),
    health: health
      ? {
          overallHealth: health.overallHealth,
          financialHealth: health.financialHealth,
          marketingHealth: health.marketingHealth,
          salesHealth: health.salesHealth,
          operationalHealth: health.operationalHealth,
          productHealth: health.productHealth,
          growthHealth: health.growthHealth,
          executiveHealth: health.executiveHealth,
        }
      : null,
    criticalDependencies: deps
      .filter((d) => !d.resolved && d.severity >= 0.7)
      .slice(0, 3)
      .map((d) => ({
        id: d.id,
        dependencyType: d.dependencyType,
        severity: d.severity,
        description: d.description,
      })),
    opportunities: findOpportunities(activeNodes, kpis, health),
    lastActivityAt,
  };
}

// ── Build the EB advisory text ────────────────────────────────────────────────

export function buildBizContextAdvisory(summary: BusinessGraphSummary | null): string | null {
  if (!summary) return null;
  if (summary.nodeCount === 0) return null;

  const lines: string[] = [
    `BUSINESS GRAPH: "${summary.businessName}" (${summary.nodeCount} nodes, ${summary.edgeCount} edges)`,
  ];

  if (summary.health) {
    const h = summary.health;
    lines.push(
      `Health: overall ${(h.overallHealth * 100).toFixed(0)}% | financial ${(h.financialHealth * 100).toFixed(0)}% | growth ${(h.growthHealth * 100).toFixed(0)}% | operational ${(h.operationalHealth * 100).toFixed(0)}%`,
    );
  }

  if (summary.topNodes.length > 0) {
    const nodeList = summary.topNodes
      .slice(0, 3)
      .map((n) => `${n.name}(${n.nodeType},${n.health})`)
      .join(", ");
    lines.push(`Key entities: ${nodeList}`);
  }

  if (summary.criticalRisks.length > 0) {
    lines.push(
      `RISKS: ${summary.criticalRisks.map((r) => `${r.name}[${r.risk}]`).join(", ")}`,
    );
  }

  if (summary.criticalDependencies.length > 0) {
    lines.push(
      `Critical dependencies: ${summary.criticalDependencies.map((d) => d.description.slice(0, 60)).join("; ")}`,
    );
  }

  if (summary.currentKpis.length > 0) {
    const kpiList = summary.currentKpis
      .filter((k) => k.currentValue != null)
      .slice(0, 3)
      .map((k) => `${k.name}=${k.currentValue}${k.unit}(${k.trend})`)
      .join(", ");
    if (kpiList) lines.push(`KPIs: ${kpiList}`);
  }

  if (summary.opportunities.length > 0) {
    lines.push(`Opportunities: ${summary.opportunities[0]}`);
  }

  return lines.join("\n");
}
