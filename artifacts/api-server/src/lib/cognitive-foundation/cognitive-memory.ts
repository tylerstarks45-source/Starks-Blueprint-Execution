// ─── Input / Output shapes ────────────────────────────────────────────────────

/** What callers provide when consolidating a new Cognitive Artifact. */
export interface CognitiveArtifactInput {
  /** UUID generated by the caller (reuses Build 003 Decision Record UUID). */
  id: string;
  artifactType: string;
  sourceBrain?: string;
  /** For artifacts derived from a decision record: the root decision id. */
  decisionId?: string;
  version?: number;
  lifecycleStatus?: string;
  confidenceOverall: OrchestrationConfidence;
  confidenceReasoning?: OrchestrationConfidence;
  confidenceCapability?: OrchestrationConfidence;
  confidenceBrainSelection?: OrchestrationConfidence;
  brainsSelected?: string[];
  capabilitiesUsed?: string[];
  evidence?: string[];
  executiveBrainVersion?: string;
  /** The complete typed payload for this artifact type. */
  content: Record<string, unknown>;
  relationships?: Record<string, unknown>;
  metadata?: Record<string, unknown>;
  /** Denormalized text extracted from content for retrieval search. */
  objectiveText?: string;
  userId?: number;
  projectId?: number;
}

/** A Cognitive Artifact as returned from the store. */
export interface StoredCognitiveArtifact {
  id: string;
  artifactType: string;
  sourceBrain: string;
  decisionId: string | null;
  version: number;
  lifecycleStatus: string;
  confidenceOverall: string;
  confidenceReasoning: string | null;
  confidenceCapability: string | null;
  confidenceBrainSelection: string | null;
  brainsSelected: string[];
  capabilitiesUsed: string[];
  evidence: string[];
  executiveBrainVersion: string | null;
  content: Record<string, unknown>;
  relationships: Record<string, unknown>;
  metadata: Record<string, unknown>;
  objectiveText: string | null;
  userId: number | null;
  projectId: number | null;
  createdAt: Date;
  updatedAt: Date;
}

function rowToArtifact(row: typeof cognitiveArtifactsTable.$inferSelect): StoredCognitiveArtifact {
  return {
    ...row,
    brainsSelected: (row.brainsSelected as string[]) ?? [],
    capabilitiesUsed: (row.capabilitiesUsed as string[]) ?? [],
    evidence: (row.evidence as string[]) ?? [],
    content: (row.content as Record<string, unknown>) ?? {},
    relationships: (row.relationships as Record<string, unknown>) ?? {},
    metadata: (row.metadata as Record<string, unknown>) ?? {},
  };
}

// ─── Cognitive Artifact Store ─────────────────────────────────────────────────

/** Persist a single Cognitive Artifact to the store. Idempotent on id:
 *  if an artifact with the same id already exists, this is a no-op (avoids
 *  duplicate writes when the consolidation pipeline is called multiple times). */
export async function storeArtifact(input: CognitiveArtifactInput): Promise<void> {
  await db
    .insert(cognitiveArtifactsTable)
    .values({
      id: input.id,
      artifactType: input.artifactType,
      sourceBrain: input.sourceBrain ?? "executive-brain",
      decisionId: input.decisionId ?? null,
      version: input.version ?? 1,
      lifecycleStatus: input.lifecycleStatus ?? "active",
      confidenceOverall: input.confidenceOverall,
      confidenceReasoning: input.confidenceReasoning ?? null,
      confidenceCapability: input.confidenceCapability ?? null,
      confidenceBrainSelection: input.confidenceBrainSelection ?? null,
      brainsSelected: input.brainsSelected ?? [],
      capabilitiesUsed: input.capabilitiesUsed ?? [],
      evidence: input.evidence ?? [],
      executiveBrainVersion: input.executiveBrainVersion ?? null,
      content: input.content,
      relationships: input.relationships ?? {},
      metadata: input.metadata ?? {},
      objectiveText: input.objectiveText ?? null,
      userId: input.userId ?? null,
      projectId: input.projectId ?? null,
    })
    .onConflictDoNothing();
}

/** Retrieve a single Cognitive Artifact by id. Returns null if not found. */
export async function getArtifact(id: string): Promise<StoredCognitiveArtifact | null> {
  const rows = await db
    .select()
    .from(cognitiveArtifactsTable)
    .where(eq(cognitiveArtifactsTable.id, id))
    .limit(1);
  return rows[0] ? rowToArtifact(rows[0]) : null;
}

/** Soft-update an artifact's lifecycle status or metadata. Used by future
 *  reflection/retention systems to mark artifacts as archived, superseded, etc.
 *  Never deletes; deletion is a human governance decision, not an AI one. */
export async function updateArtifactMetadata(
  id: string,
  patch: { lifecycleStatus?: string; metadata?: Record<string, unknown>; relationships?: Record<string, unknown> },
): Promise<void> {
  const updates: Record<string, unknown> = { updatedAt: new Date() };
  if (patch.lifecycleStatus !== undefined) updates["lifecycleStatus"] = patch.lifecycleStatus;
  if (patch.metadata !== undefined) updates["metadata"] = patch.metadata;
  if (patch.relationships !== undefined) updates["relationships"] = patch.relationships;
  await db
    .update(cognitiveArtifactsTable)
    .set(updates)
    .where(eq(cognitiveArtifactsTable.id, id));
}

// ─── Memory Consolidation Pipeline ───────────────────────────────────────────
//
// The pipeline's responsibility is deciding HOW Cognitive Artifacts enter
// long-term memory — not simply storing them. Today the policy is: persist all
// Executive Decision Records. Future builds will layer:
//   - Importance scoring (low-value artifacts filtered out)
//   - Summarization (verbose artifacts compressed)
//   - Lesson extraction (patterns distilled into ash_lessons)
//   - Retention policies (e.g. keep last 1000 per user)
//
// EXTENSION POINT: register consolidation hooks via registerConsolidationHook().

type ConsolidationHook = (artifact: CognitiveArtifactInput) => Promise<void>;
const consolidationHooks: ConsolidationHook[] = [];

/** Register a consolidation hook. Hooks run in order after the artifact is
 *  persisted. Future builds register lesson-extraction, importance-scoring, etc. */
export function registerConsolidationHook(hook: ConsolidationHook): void {
  consolidationHooks.push(hook);
}

/** Run the Memory Consolidation Pipeline for a Cognitive Artifact.
 *  1. Store the artifact (idempotent).
 *  2. Run registered consolidation hooks in order.
 *  Both steps are logged; neither throws to callers. */
export async function consolidate(input: CognitiveArtifactInput): Promise<void> {
  try {
    await storeArtifact(input);
    logger.debug(
      { artifactId: input.id, artifactType: input.artifactType, userId: input.userId },
      "Cognitive artifact consolidated to memory",
    );
  } catch (err) {
    logger.warn({ err, artifactId: input.id }, "Cognitive memory: artifact storage failed (non-fatal)");
    return; // Don't run hooks if storage failed
  }

  // Run consolidation hooks (future: filtering, scoring, lesson extraction)
  for (const hook of consolidationHooks) {
    try {
      await hook(input);
    } catch (err) {
      logger.warn({ err }, "Cognitive memory: consolidation hook failed (non-fatal)");
    }
  }
}

// ─── Cognitive Retrieval Architecture ────────────────────────────────────────
//
// Retrieval is designed as the beginning of cognition, not a database query.
// Each function is named for the cognitive question it answers, not the SQL
// it runs. Future builds upgrade the implementation (e.g. vector similarity
// for findSimilarDecisions) without changing the function signatures.

/** Filter shape for historical reasoning queries. All fields optional — omit
 *  to get the broadest possible result set. */
export interface ArtifactQuery {
  userId?: number;
  artifactType?: string;
  sourceBrain?: string;
  lifecycleStatus?: string;
  confidenceOverall?: OrchestrationConfidence;
  /** Full-text/keyword search on objective_text. */
  objectiveQuery?: string;
  /** Return artifacts where this Brain name appears in brains_selected. */
  brainParticipant?: string;
  /** Lower bound on created_at. */
  fromTime?: Date;
  /** Upper bound on created_at. */
  toTime?: Date;
  /** Retrieve specific artifact ids — used by graph traversal to batch-load
   *  artifact records for a set of known ids (neighborhood nodes). */
  ids?: string[];
  limit?: number;
  offset?: number;
}

/** Query historical Cognitive Artifacts by any combination of filter dimensions.
 *
 *  This is the primary retrieval surface for the Historical Reasoning Service.
 *  The filter signature is intentionally stable — future builds add semantic
 *  similarity, vector search, and importance ranking without changing callers. */
export async function queryArtifacts(q: ArtifactQuery): Promise<StoredCognitiveArtifact[]> {
  const conditions: SQL[] = [];

  if (q.userId !== undefined) {
    conditions.push(eq(cognitiveArtifactsTable.userId, q.userId));
  }
  if (q.artifactType !== undefined) {
    conditions.push(eq(cognitiveArtifactsTable.artifactType, q.artifactType));
  }
  if (q.sourceBrain !== undefined) {
    conditions.push(eq(cognitiveArtifactsTable.sourceBrain, q.sourceBrain));
  }
  if (q.lifecycleStatus !== undefined) {
    conditions.push(eq(cognitiveArtifactsTable.lifecycleStatus, q.lifecycleStatus));
  }
  if (q.confidenceOverall !== undefined) {
    conditions.push(eq(cognitiveArtifactsTable.confidenceOverall, q.confidenceOverall));
  }
  if (q.fromTime !== undefined) {
    conditions.push(gte(cognitiveArtifactsTable.createdAt, q.fromTime));
  }
  if (q.toTime !== undefined) {
    conditions.push(lte(cognitiveArtifactsTable.createdAt, q.toTime));
  }

  // Direct id lookup — used by graph traversal to batch-load neighborhood nodes
  if (q.ids && q.ids.length > 0) {
    conditions.push(inArray(cognitiveArtifactsTable.id, q.ids));
  }

  // Keyword search on objective_text (future: replace with vector similarity)
  if (q.objectiveQuery) {
    const tokens = q.objectiveQuery
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, " ")
      .split(/\s+/)
      .filter((t) => t.length >= 3)
      .slice(0, 10); // Cap tokens to avoid over-restriction
    if (tokens.length > 0) {
      // Use ILIKE for broad matching; future builds can upgrade to full-text or vector
      const likeConditions = tokens.map(
        (token) => sql`${cognitiveArtifactsTable.objectiveText} ILIKE ${"%" + token + "%"}`,
      );
      // OR across tokens: any match qualifies (recall over precision)
      conditions.push(sql`(${sql.join(likeConditions, sql` OR `)})`);
    }
  }

  // JSONB array contains: brains_selected @> '[brainName]'
  if (q.brainParticipant) {
    conditions.push(
      sql`${cognitiveArtifactsTable.brainsSelected} @> ${JSON.stringify([q.brainParticipant])}::jsonb`,
    );
  }

  const limit = Math.min(q.limit ?? 20, 100);
  const offset = q.offset ?? 0;

  const rows = await db
    .select()
    .from(cognitiveArtifactsTable)
    .where(conditions.length > 0 ? and(...conditions) : undefined)
    .orderBy(desc(cognitiveArtifactsTable.createdAt))
    .limit(limit)
    .offset(offset);

  return rows.map(rowToArtifact);
}

/** Count artifacts matching a query (without loading content). */
export async function countArtifacts(q: Omit<ArtifactQuery, "limit" | "offset">): Promise<number> {
  const conditions: SQL[] = [];
  if (q.userId !== undefined) conditions.push(eq(cognitiveArtifactsTable.userId, q.userId));
  if (q.artifactType !== undefined) conditions.push(eq(cognitiveArtifactsTable.artifactType, q.artifactType));
  if (q.lifecycleStatus !== undefined) conditions.push(eq(cognitiveArtifactsTable.lifecycleStatus, q.lifecycleStatus));

  const result = await db
    .select({ count: sql<number>`count(*)::int` })
    .from(cognitiveArtifactsTable)
    .where(conditions.length > 0 ? and(...conditions) : undefined);
  return result[0]?.count ?? 0;
}

// ─── Historical Reasoning Service ────────────────────────────────────────────
//
// Reusable services that answer cognitive questions from history.
// Each function is designed to answer a specific question the Executive Brain
// will ask in future builds. The answers today are keyword-based; future
// builds upgrade the implementations to learned similarity, vector search, etc.

/** "Have I solved something similar before?"
 *
 *  Keyword-based similarity on objective_text for now.
 *  EXTENSION POINT: replace with vector cosine similarity when embeddings are
 *  available (the function signature is already designed for that upgrade:
 *  callers pass the objective string, this function decides how to find matches). */
export async function findSimilarDecisions(
  objective: string,
  userId?: number,
  limit = 5,
): Promise<StoredCognitiveArtifact[]> {
  return queryArtifacts({
    artifactType: "decision_record",
    lifecycleStatus: "active",
    objectiveQuery: objective,
    userId,
    limit,
  });
}

/** "Which Brains have participated in decisions for this user?"
 *
 *  Returns artifacts where brainName appears in brains_selected.
 *  Useful for: "which Brain combinations perform best?", "has executive-brain
 *  been consistently engaged for research tasks?" */
export async function getBrainParticipationHistory(
  brainName: string,
  userId?: number,
  limit = 20,
): Promise<StoredCognitiveArtifact[]> {
  return queryArtifacts({
    artifactType: "decision_record",
    brainParticipant: brainName,
    userId,
    limit,
  });
}

/** Return all artifacts that share the same originating decision id.
 *  Enables traceability: given a decision record, find all derived artifacts
 *  (reflections, lessons, insights) that the decision produced. */
export async function getArtifactsByDecision(decisionId: string): Promise<StoredCognitiveArtifact[]> {
  const rows = await db
    .select()
    .from(cognitiveArtifactsTable)
    .where(eq(cognitiveArtifactsTable.decisionId, decisionId))
    .orderBy(desc(cognitiveArtifactsTable.createdAt));
  return rows.map(rowToArtifact);
}

/** "What decisions has the system made in the last N hours?"
 *
 *  Time-windowed retrieval for monitoring, debugging, and future pattern
 *  detection across a rolling window. */
export async function getRecentArtifactHistory(
  userId: number,
  hoursBack = 24,
  limit = 50,
): Promise<StoredCognitiveArtifact[]> {
  const fromTime = new Date(Date.now() - hoursBack * 60 * 60 * 1000);
  return queryArtifacts({
    userId,
    artifactType: "decision_record",
    lifecycleStatus: "active",
    fromTime,
    limit,
  });
}

/** Return summary statistics for a user's cognitive artifact store.
 *  Designed for the future Cognitive Memory health endpoint and the
 *  Self-Improving Brain's input ingestion. */
export async function getCognitiveMemorySummary(userId: number): Promise<{
  totalDecisions: number;
  activeDecisions: number;
  uniqueBrainCombinations: number;
  confidenceBreakdown: Record<string, number>;
}> {
  const [totalDecisions, activeDecisions] = await Promise.all([
    countArtifacts({ userId, artifactType: "decision_record" }),
    countArtifacts({ userId, artifactType: "decision_record", lifecycleStatus: "active" }),
  ]);

  // Confidence breakdown across active decisions
  const result = await db
    .select({
      confidence: cognitiveArtifactsTable.confidenceOverall,
      count: sql<number>`count(*)::int`,
    })
    .from(cognitiveArtifactsTable)
    .where(
      and(
        eq(cognitiveArtifactsTable.userId, userId),
        eq(cognitiveArtifactsTable.artifactType, "decision_record"),
        eq(cognitiveArtifactsTable.lifecycleStatus, "active"),
      ),
    )
    .groupBy(cognitiveArtifactsTable.confidenceOverall);

  const confidenceBreakdown: Record<string, number> = {};
  for (const row of result) {
    if (row.confidence) confidenceBreakdown[row.confidence] = row.count;
  }

  // Unique Brain combination count (approximate: count distinct brainsSelected JSON arrays)
  const uniqueResult = await db
    .select({ count: sql<number>`count(distinct brains_selected::text)::int` })
    .from(cognitiveArtifactsTable)
    .where(
      and(
        eq(cognitiveArtifactsTable.userId, userId),
        eq(cognitiveArtifactsTable.artifactType, "decision_record"),
      ),
    );
  const uniqueBrainCombinations = uniqueResult[0]?.count ?? 0;

  return { totalDecisions, activeDecisions, uniqueBrainCombinations, confidenceBreakdown };
}
