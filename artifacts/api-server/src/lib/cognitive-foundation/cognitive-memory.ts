// ─── Cognitive Memory Architecture (Build 004) ───────────────────────────────
//
// The first permanent, durable memory layer for ASH Executive cognition.
// Implements the "Record → Consolidate → Retrieve" stages of the Cognitive
// Lifecycle defined in the Build 004 specification.
//
// Architecture:
//   Cognitive Lifecycle: Observe → Reason → Decide → Record → Consolidate →
//                        Retrieve → Reflect → Learn → Improve
//
//   This module is responsible for:
//     - Consolidate: deciding how Cognitive Artifacts enter long-term memory.
//     - Retrieve: querying historical reasoning by any metadata dimension.
//
//   "Reflect → Learn → Improve" are future builds; this module is explicitly
//   designed to be their foundation. No autonomous logic is implemented here.
//
// Design invariants:
//   - Never blocks the request path: all DB writes are fire-and-forget.
//   - Fail-open: every DB operation catches its own errors with a log.
//   - Single unified table (cognitive_artifacts) with a type discriminator:
//     future artifact types add no schema changes, only new type constants.
//   - All retrieval functions are composable by filter: future learning layers
//     query by brain participation, confidence, similarity, etc.
//   - Text similarity (findSimilarDecisions) is keyword-based today;
//     the function signature is already designed for vector search upgrade.

import { db, cognitiveArtifactsTable } from "@workspace/db";
import { eq, and, desc, gte, lte, sql, inArray, type SQL } from "drizzle-orm";
import { logger } from "../logger";
