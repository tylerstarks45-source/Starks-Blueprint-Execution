// ── Public accessor ────────────────────────────────────────────────────────
export function getLifecycleCatalog(): LifecycleRecord[] {
  return LIFECYCLE_CATALOG;
}

// ── Composite maturity score from lifecycle record ─────────────────────────
export function computeOverallMaturity(lc: LifecycleRecord): number {
  return Math.round((lc.maturityScore + lc.stabilityScore + lc.longevityScore) / 3 * 1000) / 1000;
}

// ── Technologies in declining/legacy/eol stages ────────────────────────────
export function getDeprecationCandidates(catalog: LifecycleRecord[]): string[] {
  return catalog
    .filter(lc => lc.lifecycleStage === "declining" || lc.lifecycleStage === "legacy" || lc.lifecycleStage === "end-of-life")
    .map(lc => lc.technologyKey);
}

// ── Technologies in experimental/emerging stages ───────────────────────────
export function getEmergingTechnologies(catalog: LifecycleRecord[]): string[] {
  return catalog
    .filter(lc => lc.lifecycleStage === "experimental" || lc.lifecycleStage === "emerging")
    .map(lc => lc.technologyKey);
}
