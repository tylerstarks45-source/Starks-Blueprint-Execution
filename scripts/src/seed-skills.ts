async function seedSkills() {
  console.log(`Seeding ${SKILLS.length} skills...`);
  let inserted = 0;
  let skipped = 0;

  for (const skill of SKILLS) {
    const existing = await db
      .select({ id: skillsTable.id })
      .from(skillsTable)
      .where(eq(skillsTable.slug, skill.slug));

    if (existing.length > 0) {
      skipped++;
      continue;
    }

    await db.insert(skillsTable).values(skill);
    inserted++;
    console.log(`  ✓ ${skill.name}`);
  }

  console.log(`\nDone: ${inserted} inserted, ${skipped} already existed`);
  process.exit(0);
}

seedSkills().catch((err) => {
  console.error(err);
  process.exit(1);
});
